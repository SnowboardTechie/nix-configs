def esc(value: object) -> str:
    return html.escape(str(value), quote=True)


def display_date(moment: dt.datetime) -> str:
    return moment.strftime("%Y-%m-%d")


def render_card(record: dict) -> str:
    slug = record["slug"]
    item = items_dir() / slug
    href = f"{slug}/" if record["entry"] == DEFAULT_ENTRY else f"{slug}/{urllib.parse.quote(record['entry'])}"
    project = str(record.get("project") or UNLABELED)
    title = str(record.get("title") or slug)
    parts = [f'<li class="card" data-project="{esc(project)}">']
    for name in THUMBNAILS:
        if (item / name).is_file():
            parts.append(f'<a href="{esc(href)}" tabindex="-1"><img src="{esc(slug)}/{name}" alt="" loading="lazy"></a>')
            break
    parts.append('<div class="body">')
    parts.append(f'<a href="{esc(href)}">{esc(title)}</a><br>')
    parts.append(f'<span class="project">{esc(project)}</span>')
    if record.get("description"):
        parts.append(f'<p class="desc">{esc(record["description"])}</p>')
    when = f"Updated {display_date(record['sort_time'])}"
    created = record.get("created")
    if isinstance(created, str):
        try:
            created_date = display_date(parse_time(created))
        except ValueError:
            created_date = None
        if created_date and created_date != display_date(record["sort_time"]):
            when += f" · created {created_date}"
    parts.append(f'<p class="when">{esc(when)}</p></div></li>')
    return "".join(parts)


def render_index(records: list[dict]) -> str:
    shown = [r for r in records if r["status"] == "ok"]
    cutoff = now() - dt.timedelta(days=older_days())
    recent = [r for r in shown if r["sort_time"] >= cutoff]
    older = [r for r in shown if r["sort_time"] < cutoff]
    out = [
        "<!doctype html>",
        '<html lang="en"><head><meta charset="utf-8">',
        '<meta name="viewport" content="width=device-width,initial-scale=1">',
        f'<meta name="generator" content="{GENERATOR}">',
        '<meta name="robots" content="noindex,nofollow">',
        "<title>Artifact Shelf</title>",
        f"<style>{STYLE}</style></head><body><main>",
        "<h1>Artifact Shelf</h1>",
    ]
    if not shown:
        out.append('<p class="empty">Nothing is on the shelf yet.</p>')
    else:
        # The newest item's time, not the generation time: an unchanged shelf
        # renders byte-identical, so rewriting it never retriggers WatchPaths.
        noun = "artifact" if len(shown) == 1 else "artifacts"
        newest = shown[0]["sort_time"].strftime("%Y-%m-%d %H:%M")
        out.append(f'<p class="count">{len(shown)} {noun}, updated {esc(newest)}</p>')
        projects = sorted({str(r.get("project") or UNLABELED) for r in shown}, key=str.lower)
        chips = ['<div class="chips" hidden><button type="button" data-project="" aria-pressed="true">All</button>']
        chips += [
            f'<button type="button" data-project="{esc(p)}" aria-pressed="false">{esc(p)}</button>'
            for p in projects
        ]
        chips.append("</div>")
        out.append("".join(chips))
        if recent:
            out.append("<h2>Recent</h2>")
            out.append('<ul class="grid">' + "".join(render_card(r) for r in recent) + "</ul>")
        if older:
            out.append(f"<details><summary>Older ({len(older)})</summary>")
            out.append('<ul class="grid">' + "".join(render_card(r) for r in older) + "</ul></details>")
        out.append(f"<script>{SCRIPT}</script>")
    out.append("</main></body></html>")
    return "\n".join(out) + "\n"


def write_index() -> Path:
    ensure_layout()
    page = render_index(collect())
    target = items_dir() / "index.html"
    try:
        if target.read_text(encoding="utf-8") == page:
            return target
    except OSError:
        pass
    # The temp file lives beside items/, outside the served tree.
    atomic_write(target, page, temp_dir=root())
    return target


# --- commands ----------------------------------------------------------------


def check_source(src: Path) -> Path:
    if not src.is_dir():
        raise ShelfError(f"source {src} is not a directory")
    resolved = src.resolve()
    shelf = root().resolve()
    if resolved == shelf or resolved.is_relative_to(shelf) or shelf.is_relative_to(resolved):
        raise ShelfError("source must be outside the shelf root")
    return resolved


def check_inner_links(tree: Path) -> None:
    """Refuse a tree holding a symlink that could lead outside it.

    Caddy follows symlinks, so a link to ~/.ssh or similar would serve that
    file on the tailnet. Every link must be relative and resolve inside the
    tree; absolute links are refused even when they point inside, because a
    copy would keep pointing back at the (mutable, possibly pruned) source.
    A directory the walk can't read refuses the tree rather than being
    skipped.
    """
    tree = tree.resolve()

    def unreadable(error: OSError) -> None:
        raise ShelfError(f"refusing {tree}: cannot inspect {error.filename}: {error.strerror}")

    for directory, dirnames, filenames in os.walk(tree, onerror=unreadable, followlinks=False):
        for name in dirnames + filenames:
            path = Path(directory) / name
            if not path.is_symlink():
                continue
            text = os.readlink(path)
            if os.path.isabs(text):
                raise ShelfError(f"refusing {path}: absolute symlink ({text}); use a relative link inside the source")
            try:
                target = path.resolve(strict=True)
            except (OSError, RuntimeError):
                raise ShelfError(f"refusing {path}: broken or looping symlink")
            if not target.is_relative_to(tree):
                raise ShelfError(f"refusing {path}: symlink points outside the source, to {target}")


def under_pruned(path: Path) -> Path | None:
    for candidate in pruned_roots():
        for form in {candidate, candidate.resolve()}:
            if path == form or path.is_relative_to(form):
                return candidate
    return None


def swap_into_place(staged: Path, target: Path) -> None:
    """Move staged into target, replacing what is there with the shortest gap."""
    if not os.path.lexists(target):
        os.rename(staged, target)
        return
    if staged.is_symlink() and target.is_symlink():
        os.replace(staged, target)  # atomic for link over link
        return
    aside = target.with_name(f".{target.name}.old-{os.getpid()}")
    os.rename(target, aside)
    os.rename(staged, target)
    remove_path(aside)


def cmd_publish(args: argparse.Namespace) -> int:
    ensure_layout()
    slug = normalize_slug(args.slug)
    entry = args.entry
    if not valid_entry(entry):
        raise ShelfError(f"invalid entry {entry!r}: use a relative path inside the source")
    src = check_source(Path(args.src))
    if not (src / entry).is_file():
        raise ShelfError(f"entry {entry!r} not found in {src}")
    check_inner_links(src)
    if args.link:
        pruned = under_pruned(src)
        if pruned is not None:
            raise ShelfError(f"refusing --link: {src} is under {pruned}, which gets pruned; publish without --link to copy it")

    target = items_dir() / slug
    existing = read_meta(slug)
    if (os.path.lexists(target) or existing is not None) and not args.replace:
        raise ShelfError(f"{slug} is already on the shelf; pass --replace to swap it")

    staged = items_dir() / f".staging-{slug}-{os.getpid()}"
    if os.path.lexists(staged):
        remove_path(staged)
    try:
        if args.link:
            os.symlink(src, staged)
        else:
            shutil.copytree(src, staged, symlinks=True)
            # Check what will actually be served, not just the source, which
            # can change between the first check and the copy.
            check_inner_links(staged)
        swap_into_place(staged, target)
    finally:
        if os.path.lexists(staged):
            remove_path(staged)

    stamp = iso(now())
    created = existing.get("created") if existing and isinstance(existing.get("created"), str) else stamp
    write_meta(
        {
            "slug": slug,
            "title": args.title,
            "project": args.project,
            "description": args.description,
            "entry": entry,
            "created": created,
            "updated": stamp,
            "linked": bool(args.link),
            "source": str(src),
        }
    )
    print(item_url(slug, entry))
    write_index()
    return 0


def cmd_touch(args: argparse.Namespace) -> int:
    slug = require_slug(args.slug)
    record = read_meta(slug)
    if record is None:
        raise ShelfError(f"{slug} has no record; publish it with --replace to label it")
    record["updated"] = iso(now())
    write_meta(record)
    write_index()
    return 0


def cmd_retire(args: argparse.Namespace) -> int:
    ensure_layout()
    slug = require_slug(args.slug)
    item = items_dir() / slug
    meta = meta_path(slug)
    if not os.path.lexists(item) and not meta.exists():
        raise ShelfError(f"{slug} is not on the shelf")
    stem = f"{slug}-{now().strftime('%Y%m%dT%H%M%S')}"
    destination = retired_dir() / stem
    suffix = 1
    while os.path.lexists(destination):
        destination = retired_dir() / f"{stem}-{suffix}"
        suffix += 1
    destination.mkdir(parents=True)
    # os.rename moves a symlink itself, never its target.
    if os.path.lexists(item):
        os.rename(item, destination / slug)
    if meta.exists():
        os.rename(meta, destination / meta.name)
    print(destination)
    write_index()
    return 0


def public(record: dict) -> dict:
    keys = ("slug", "title", "project", "description", "url", "entry", "created", "updated", "linked", "source", "status")
    result = {key: record.get(key) for key in keys if key in record}
    result["updated"] = record.get("updated") or iso(record["sort_time"])
    result["linked"] = bool(record.get("linked"))
    return result


def cmd_list(args: argparse.Namespace) -> int:
    records = [public(r) for r in collect()]
    if args.json:
        print(json.dumps(records, indent=2))
        return 0
    if not records:
        print("Nothing is on the shelf yet.")
        return 0
    for r in records:
        link = "link" if r["linked"] else "copy"
        print(f"{r['status']:<7} {link:<4} {r['updated']:<25} {r['slug']}  {r['title']}  {r['url']}")
    return 0


def cmd_url(args: argparse.Namespace) -> int:
    slug = require_slug(args.slug)
    record = read_meta(slug)
    if record is None and not os.path.lexists(items_dir() / slug):
        raise ShelfError(f"{slug} is not on the shelf")
    entry = str((record or {}).get("entry") or DEFAULT_ENTRY)
    print(item_url(slug, entry if valid_entry(entry) else DEFAULT_ENTRY))
    return 0


def cmd_index(_args: argparse.Namespace) -> int:
    write_index()
    return 0


def parser() -> argparse.ArgumentParser:
    top = argparse.ArgumentParser(prog="artifact-shelf", description="Publish pages to the Artifact Shelf.")
    sub = top.add_subparsers(dest="command", required=True)

    publish = sub.add_parser("publish", help="put a directory on the shelf")
    publish.add_argument("src")
    publish.add_argument("--slug", required=True, help="YYYY-MM-DD-name; today's date is added when absent")
    publish.add_argument("--title", required=True)
    publish.add_argument("--project", required=True)
    publish.add_argument("--description", required=True)
    publish.add_argument("--link", action="store_true", help="symlink the source instead of copying it")
    publish.add_argument("--entry", default=DEFAULT_ENTRY, help="page to open, relative to SRC")
    publish.add_argument("--replace", action="store_true", help="swap an existing item, keeping its created time")
    publish.set_defaults(func=cmd_publish)

    for name, func, text in (
        ("touch", cmd_touch, "bump an item's updated time"),
        ("retire", cmd_retire, "move an item off the shelf"),
        ("url", cmd_url, "print an item's URL"),
    ):
        command = sub.add_parser(name, help=text)
        command.add_argument("slug")
        command.set_defaults(func=func)

    listing = sub.add_parser("list", help="every item with its status")
    listing.add_argument("--json", action="store_true")
    listing.set_defaults(func=cmd_list)

    index = sub.add_parser("index", help="regenerate items/index.html")
    index.set_defaults(func=cmd_index)
    return top


def main(argv: list[str] | None = None) -> int:
    args = parser().parse_args(argv)
    try:
        return args.func(args)
    except ShelfError as error:
        print(f"artifact-shelf: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
