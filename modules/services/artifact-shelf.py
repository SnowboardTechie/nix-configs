#!/usr/bin/env python3
"""Artifact Shelf: publish, list and index the pages Hermes prepares.

Layout under ARTIFACT_SHELF_ROOT:
  items/<slug>/        served by Caddy (a copied directory or a symlink)
  items/index.html     the shelf page, regenerated by `index`
  meta/<slug>.json     one record per item, not served
  retired/             retired items and their records, not served

Stdlib only; runs under Nix's python3Minimal.
"""

from __future__ import annotations

import argparse
import datetime as dt
import html
import json
import os
import re
import shutil
import sys
import tempfile
import urllib.parse
from pathlib import Path

GENERATOR = "artifact-shelf"
DEFAULT_ENTRY = "index.html"
UNLABELED = "Unlabeled"
THUMBNAILS = ("shelf-thumb.png", "shelf-thumb.jpg")
SLUG_BODY = r"[a-z0-9]+(?:-[a-z0-9]+)*"
SLUG_RE = re.compile(r"^(\d{4}-\d{2}-\d{2})-" + SLUG_BODY + r"$")
BODY_RE = re.compile(r"^" + SLUG_BODY + r"$")
MAX_SLUG = 120
# Sources here are pruned, so a link into them would die: copy instead.
DEFAULT_PRUNED = ("/tmp", "/private/tmp", "/var/folders", "/private/var/folders")


class ShelfError(Exception):
    pass


# --- configuration -----------------------------------------------------------


def root() -> Path:
    value = os.environ.get("ARTIFACT_SHELF_ROOT")
    if not value:
        raise ShelfError("ARTIFACT_SHELF_ROOT is not set")
    return Path(value)


def base_url() -> str:
    return os.environ.get("ARTIFACT_SHELF_URL", "http://127.0.0.1:8092").rstrip("/")


def older_days() -> int:
    return int(os.environ.get("ARTIFACT_SHELF_OLDER_DAYS", "30"))


def now() -> dt.datetime:
    # ARTIFACT_SHELF_NOW pins the clock for tests.
    pinned = os.environ.get("ARTIFACT_SHELF_NOW")
    if pinned:
        return parse_time(pinned)
    return dt.datetime.now().astimezone().replace(microsecond=0)


def pruned_roots() -> list[Path]:
    extra = os.environ.get("ARTIFACT_SHELF_PRUNED_DIRS")
    roots = [Path(p) for p in extra.split(":") if p] if extra is not None else [Path(p) for p in DEFAULT_PRUNED]
    roots.append(Path.home() / ".hermes" / "cache" / "scratch")
    return roots


def items_dir() -> Path:
    return root() / "items"


def meta_dir() -> Path:
    return root() / "meta"


def retired_dir() -> Path:
    return root() / "retired"


def ensure_layout() -> None:
    for path in (items_dir(), meta_dir(), retired_dir()):
        path.mkdir(parents=True, exist_ok=True)


# --- validation --------------------------------------------------------------


def valid_slug(slug: str) -> bool:
    match = SLUG_RE.match(slug)
    if not match or len(slug) > MAX_SLUG:
        return False
    try:
        dt.date.fromisoformat(match.group(1))
    except ValueError:
        return False
    return True


def normalize_slug(name: str) -> str:
    """Return a dated slug for NAME, or raise. Adds today's date when absent."""
    if valid_slug(name):
        return name
    if re.match(r"^\d{4}-\d{2}-\d{2}-", name):
        raise ShelfError(f"invalid slug {name!r}: bad date or characters")
    if not BODY_RE.match(name):
        raise ShelfError(
            f"invalid slug {name!r}: use lowercase a-z, 0-9 and single hyphens"
        )
    slug = f"{now().date().isoformat()}-{name}"
    if not valid_slug(slug):
        raise ShelfError(f"invalid slug {name!r}: too long")
    return slug


def require_slug(slug: str) -> str:
    if not valid_slug(slug):
        raise ShelfError(f"invalid slug {slug!r}")
    return slug


def valid_entry(entry: str) -> bool:
    if not entry or entry.startswith("/") or "\\" in entry or "\0" in entry:
        return False
    parts = entry.split("/")
    return all(part not in ("", ".", "..") for part in parts)


def parse_time(value: str) -> dt.datetime:
    parsed = dt.datetime.fromisoformat(value)
    if parsed.tzinfo is None:
        parsed = parsed.astimezone()
    return parsed


def iso(moment: dt.datetime) -> str:
    return moment.isoformat(timespec="seconds")


# --- records -----------------------------------------------------------------


def item_url(slug: str, entry: str = DEFAULT_ENTRY) -> str:
    url = f"{base_url()}/{slug}/"
    if entry != DEFAULT_ENTRY:
        url += urllib.parse.quote(entry)
    return url


def meta_path(slug: str) -> Path:
    return meta_dir() / f"{slug}.json"


def read_meta(slug: str) -> dict | None:
    path = meta_path(slug)
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError:
        return None
    except (OSError, ValueError) as error:
        print(f"artifact-shelf: ignoring unreadable {path}: {error}", file=sys.stderr)
        return None
    return value if isinstance(value, dict) else None


def atomic_write(path: Path, text: str, temp_dir: Path | None = None) -> None:
    directory = temp_dir or path.parent
    descriptor, temp_name = tempfile.mkstemp(prefix=f".{path.name}.", suffix=".tmp", dir=directory)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        os.chmod(temp_name, 0o644)
        os.replace(temp_name, path)
    finally:
        if os.path.lexists(temp_name):
            os.unlink(temp_name)


def write_meta(record: dict) -> None:
    atomic_write(meta_path(record["slug"]), json.dumps(record, indent=2, sort_keys=True) + "\n")


def remove_path(path: Path) -> None:
    """Remove a directory, file or symlink, never following a symlink."""
    if path.is_symlink() or path.is_file():
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)


def item_status(slug: str, entry: str) -> str:
    item = items_dir() / slug
    if not os.path.lexists(item):
        return "missing"
    if not valid_entry(entry):
        return "missing"
    # Path.is_file follows symlinks: a broken link reads as missing.
    return "ok" if (item / entry).is_file() else "missing"


def collect() -> list[dict]:
    """Every meta record plus every unlabeled item directory, with status."""
    records: dict[str, dict] = {}
    if meta_dir().is_dir():
        for path in sorted(meta_dir().glob("*.json")):
            slug = path.name[: -len(".json")]
            if not valid_slug(slug):
                continue
            record = read_meta(slug)
            if record is None:
                continue
            record["slug"] = slug
            record.setdefault("entry", DEFAULT_ENTRY)
            record["labeled"] = True
            records[slug] = record
    if items_dir().is_dir():
        for path in sorted(items_dir().iterdir()):
            slug = path.name
            if slug in records or not valid_slug(slug):
                continue
            records[slug] = {
                "slug": slug,
                "title": slug,
                "project": UNLABELED,
                "description": "",
                "entry": DEFAULT_ENTRY,
                "linked": path.is_symlink(),
                "labeled": False,
            }
    result = []
    for slug, record in records.items():
        entry = str(record.get("entry") or DEFAULT_ENTRY)
        record["entry"] = entry
        record["status"] = item_status(slug, entry)
        record["url"] = item_url(slug, entry) if valid_entry(entry) else item_url(slug)
        record["sort_time"] = sort_time(record)
        result.append(record)
    result.sort(key=lambda r: (r["sort_time"], r["slug"]), reverse=True)
    return result


def sort_time(record: dict) -> dt.datetime:
    for key in ("updated", "created"):
        value = record.get(key)
        if isinstance(value, str):
            try:
                return parse_time(value)
            except ValueError:
                pass
    entry_file = items_dir() / record["slug"] / record["entry"]
    try:
        return dt.datetime.fromtimestamp(entry_file.stat().st_mtime).astimezone().replace(microsecond=0)
    except (OSError, ValueError):
        return dt.datetime.fromtimestamp(0).astimezone()


